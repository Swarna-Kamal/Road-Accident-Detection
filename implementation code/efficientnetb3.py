class ChannelAttention(nn.Module):
    def __init__(self, channels, reduction=16):
        super().__init__()
        mid = max(channels // reduction, 8)
        self.mlp = nn.Sequential(
            nn.Linear(channels, mid, bias=False),
            nn.ReLU(inplace=True),
            nn.Linear(mid, channels, bias=False),
        )

    def forward(self, x):
        avg = x.mean(dim=[2, 3])
        mx = x.amax(dim=[2, 3])
        return torch.sigmoid(self.mlp(avg) + self.mlp(mx)).unsqueeze(-1).unsqueeze(-1)


class SpatialAttention(nn.Module):
    def __init__(self, kernel=7):
        super().__init__()
        self.conv = nn.Conv2d(2, 1, kernel, padding=kernel//2, bias=False)

    def forward(self, x):
        cat = torch.cat([x.mean(dim=1, keepdim=True),
                         x.amax(dim=1, keepdim=True)], dim=1)
        return torch.sigmoid(self.conv(cat))


class CBAM(nn.Module):
    def __init__(self, channels):
        super().__init__()
        self.ca = ChannelAttention(channels)
        self.sa = SpatialAttention()

    def forward(self, x):
        x = x * self.ca(x)
        x = x * self.sa(x)
        return x

class AccidentDetector(nn.Module):
    BACKBONE_CHANNELS = 1536

    def __init__(self, num_classes=2, pretrained=True, dropout=0.4):
        super().__init__()
        self.backbone = timm.create_model(
            "efficientnet_b3",
            pretrained=pretrained,
            num_classes=0,
            global_pool=""
        )
        self.cbam = CBAM(self.BACKBONE_CHANNELS)
        self.pool = nn.AdaptiveAvgPool2d(1)
        self.dropout = nn.Dropout(dropout)
        self.head = nn.Linear(self.BACKBONE_CHANNELS, num_classes)

    def forward(self, x):
        feat = self.backbone.forward_features(x)
        feat = self.cbam(feat)
        feat = self.pool(feat).flatten(1)
        feat = self.dropout(feat)
        return self.head(feat)

class FocalLoss(nn.Module):
    def __init__(self, gamma=2.0, label_smoothing=0.1, weight=None):
        super().__init__()
        self.gamma = gamma
        self.ls = label_smoothing
        self.weight = weight

    def forward(self, logits, targets):
        num_cls = logits.size(1)

        with torch.no_grad():
            smooth_targets = torch.full_like(logits, self.ls / (num_cls - 1))
            smooth_targets.scatter_(1, targets.unsqueeze(1), 1.0 - self.ls)

        log_probs = F.log_softmax(logits, dim=1)
        probs = log_probs.exp()
        focal_w = (1.0 - probs) ** self.gamma

        loss = -(smooth_targets * focal_w * log_probs).sum(dim=1)

        if self.weight is not None:
            loss *= self.weight[targets]

        return loss.mean()

INPUT_SIZE = 300

def make_transforms():
    mean = [0.485, 0.456, 0.406]
    std  = [0.229, 0.224, 0.225]

    train_tf = transforms.Compose([
        transforms.Resize((INPUT_SIZE, INPUT_SIZE)),
        transforms.RandomHorizontalFlip(),
        transforms.RandomRotation(10),
        transforms.ToTensor(),
        transforms.Normalize(mean, std),
    ])

    val_tf = transforms.Compose([
        transforms.Resize((INPUT_SIZE, INPUT_SIZE)),
        transforms.ToTensor(),
        transforms.Normalize(mean, std),
    ])

    return train_tf, val_tf


def load_data(data_dir, batch_size=32):
    train_tf, val_tf = make_transforms()

    train_ds = datasets.ImageFolder(Path(data_dir) / "train", transform=train_tf)
    test_ds  = datasets.ImageFolder(Path(data_dir) / "test", transform=val_tf)

    sampler = WeightedRandomSampler(
        [1.0 / np.bincount([s[1] for s in train_ds.samples])[s[1]]
         for s in train_ds.samples],
        len(train_ds),
        replacement=True
    )

    train_loader = DataLoader(train_ds, batch_size=batch_size, sampler=sampler)
    test_loader  = DataLoader(test_ds, batch_size=batch_size, shuffle=False)

    return train_loader, test_loader, train_ds.classes

def train(model, train_loader, test_loader, device, epochs=20):

    counts = np.bincount([s[1] for s in train_loader.dataset.samples])
    weights = torch.tensor(counts.sum() / (len(counts) * counts), dtype=torch.float32).to(device)

    criterion = FocalLoss(weight=weights)
    optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4)

    for epoch in range(epochs):
        print(f"\nEpoch {epoch+1}/{epochs}")

        for phase, loader in [("train", train_loader), ("val", test_loader)]:
            model.train() if phase == "train" else model.eval()

            total_loss = 0
            correct = 0
            total = 0

            for imgs, labels in loader:
                imgs, labels = imgs.to(device), labels.to(device)

                optimizer.zero_grad()

                with torch.set_grad_enabled(phase == "train"):
                    outputs = model(imgs)
                    loss = criterion(outputs, labels)

                    if phase == "train":
                        loss.backward()
                        optimizer.step()

                total_loss += loss.item() * imgs.size(0)
                correct += (outputs.argmax(1) == labels).sum().item()
                total += imgs.size(0)

            print(f"{phase} loss: {total_loss/total:.4f} acc: {correct/total:.4f}")

def evaluate(model, loader, device, class_names):
    model.eval()
    preds, gts = [], []

    with torch.no_grad():
        for imgs, labels in loader:
            outputs = model(imgs.to(device))
            preds.extend(outputs.argmax(1).cpu().numpy())
            gts.extend(labels.numpy())

    print(confusion_matrix(gts, preds))
    print(classification_report(gts, preds, target_names=class_names))



