import torch
import torch.nn.functional as F
import numpy as np
import cv2
import matplotlib.pyplot as plt
from torchvision import transforms
from PIL import Image

class GradCAM:
    def __init__(self, model, target_layer):
        self.model = model
        self.target_layer = target_layer

        self.activations = None

        # Only forward hook (safe)
        self.target_layer.register_forward_hook(self.forward_hook)

    def forward_hook(self, module, input, output):
        self.activations = output

    def generate(self, input_tensor, class_idx=None):
        self.model.eval()

        output = self.model(input_tensor)

        if class_idx is None:
            class_idx = output.argmax(dim=1)

        # Get gradients w.r.t. activations
        grads = torch.autograd.grad(
            outputs=output[:, class_idx],
            inputs=self.activations,
            grad_outputs=torch.ones_like(output[:, class_idx]),
            retain_graph=True,
            create_graph=False
        )[0]

        activations = self.activations

        weights = grads.mean(dim=(2, 3), keepdim=True)
        cam = (weights * activations).sum(dim=1)

        cam = torch.relu(cam)
        cam = cam.squeeze().detach().cpu().numpy()

        cam = (cam - cam.min()) / (cam.max() + 1e-8)

        return cam


def show_gradcam(image_path, model, device, class_names):
    img = Image.open(image_path).convert("RGB")

    transform = transforms.Compose([
        transforms.Resize((300, 300)),
        transforms.ToTensor(),
    ])

    input_tensor = transform(img).unsqueeze(0).to(device)

    gradcam = GradCAM(model, model.cbam)
    cam = gradcam.generate(input_tensor)

    # Resize CAM
    cam = cv2.resize(cam, (300, 300))

    img_np = np.array(img.resize((300, 300)))

    heatmap = cv2.applyColorMap(np.uint8(255 * cam), cv2.COLORMAP_JET)
    overlay = heatmap * 0.4 + img_np
    overlay = overlay / overlay.max()

    # Prediction
    model.eval()
    with torch.no_grad():
        output = model(input_tensor)
        probs = F.softmax(output, dim=1)[0]
        pred = probs.argmax().item()

    plt.figure(figsize=(6,6))
    plt.imshow(overlay)
    plt.title(f"{class_names[pred]} ({probs[pred]:.3f})")
    plt.axis("off")
    plt.show()


